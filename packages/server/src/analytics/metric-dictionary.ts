import type { BehaviorEventName } from "@ai-hub/contracts";
import type { AnalyticsMetricDefinition } from "./aggregation.types.js";

const count = (
  metricKey: string,
  label: string,
  sourceEventNames: readonly BehaviorEventName[],
  requiredPermission: string,
  audienceRule: string,
  aggregation: AnalyticsMetricDefinition["aggregation"] = "count",
): AnalyticsMetricDefinition => ({
  metricKey,
  version: 1,
  label,
  sourceEventNames,
  aggregation,
  formula:
    aggregation === "distinct_actor"
      ? "count(distinct actor) grouped by UTC day and audience scope"
      : aggregation === "distinct_aggregate"
        ? "count(distinct aggregate) grouped by UTC day and audience scope"
        : aggregation === "snapshot"
          ? "read model snapshot query with date-range scope"
          : "count(distinct idempotency_key) grouped by UTC day and audience scope",
  timeRange: "180d",
  requiredPermission,
  audienceRule,
  recompute:
    "Read retained raw events for the requested range and replace matching daily rows.",
});

